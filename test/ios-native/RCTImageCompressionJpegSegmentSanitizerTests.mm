#import <Foundation/Foundation.h>

#import "RCTImageCompressionJpegSegmentSanitizer.h"

#include <initializer_list>

static NSUInteger RCTJpegSanitizerAssertionCount = 0;
static NSUInteger RCTJpegSanitizerFailureCount = 0;

static void RCTJpegSanitizerAssert(BOOL condition, NSString *context)
{
  RCTJpegSanitizerAssertionCount += 1;
  if (!condition) {
    RCTJpegSanitizerFailureCount += 1;
    fprintf(stderr, "FAIL: %s\n", context.UTF8String);
  }
}

static NSData *RCTJpegSanitizerData(std::initializer_list<uint8_t> bytes)
{
  return [NSData dataWithBytes:bytes.begin() length:bytes.size()];
}

static void RCTJpegSanitizerAssertEqualData(
  NSData *actual,
  NSData *expected,
  NSString *context
) {
  RCTJpegSanitizerAssert(
    actual != nil && [actual isEqualToData:expected],
    [NSString stringWithFormat:
      @"%@ (actual=%@ expected=%@)",
      context,
      actual,
      expected
    ]
  );
}

