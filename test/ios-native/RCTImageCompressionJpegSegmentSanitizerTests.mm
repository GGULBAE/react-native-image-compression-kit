  });
}

static void TestRemovesMetadataBeforeAndBetweenScans(void)
{
  NSData *actual = [RCTImageCompressionJpegSegmentSanitizer
    sanitizeJpegData:RCTMetadataRichMultiScanJpeg()
    stripRequested:YES
  ];
  NSData *expected = RCTJpegSanitizerData({
    0xff, 0xd8,
    0xff, 0xe0, 0x00, 0x04, 0x10, 0x11,
    0xff, 0xe2, 0x00, 0x05, 0x49, 0x43, 0x43,
    0xff, 0xdb, 0x00, 0x04, 0x50, 0x51,
    0xff, 0xda, 0x00, 0x08, 0x01, 0x01, 0x00, 0x00, 0x3f, 0x00,
    0xa1, 0xff, 0x00, 0xa2, 0xff, 0xd0, 0xa3,
    0xff, 0xc4, 0x00, 0x04, 0x70, 0x71,
    0xff, 0xda, 0x00, 0x08, 0x01, 0x01, 0x00, 0x00, 0x3f, 0x00,
    0xb1, 0xff, 0xd7, 0xb2,
    0xff, 0xd9,
  });
  RCTJpegSanitizerAssertEqualData(
    actual,
    expected,
    @"removes APP1, APP13, and COM around multiple scans"
  );
}

static void TestPreservesStuffedRestartAndNonSensitiveSegments(void)
{
  NSData *input = RCTJpegSanitizerData({
    0xff, 0xd8,
    0xff, 0xff, 0xe0, 0x00, 0x02,
    0xff, 0xe2, 0x00, 0x04, 0x11, 0x22,
    0xff, 0xec, 0x00, 0x04, 0x33, 0x44,
    0xff, 0x01,
    0xff, 0xda, 0x00, 0x08, 0x01, 0x01, 0x00, 0x00, 0x3f, 0x00,
    0x55, 0xff, 0x00, 0x66, 0xff, 0xd1, 0x77, 0xff, 0x01, 0x88,
    0xff, 0xdc, 0x00, 0x04, 0x00, 0x08, 0x99,
    0xff, 0xff, 0xd9,
  });
  NSData *actual = [RCTImageCompressionJpegSegmentSanitizer
    sanitizeJpegData:input
    stripRequested:YES
  ];
  RCTJpegSanitizerAssertEqualData(
    actual,
    input,
    @"preserves APP0, ICC/APP2, other APP markers, fill, TEM, DNL, stuffed bytes, and restart markers"
  );
}

static void TestBypassesSafeAndPreserveOutputs(void)
{
  NSData *input = RCTMetadataRichMultiScanJpeg();
  NSData *safe = [RCTImageCompressionJpegSegmentSanitizer
    sanitizeJpegData:input
    stripRequested:NO
  ];
  NSData *preserve = [RCTImageCompressionJpegSegmentSanitizer
    sanitizeJpegData:input
    stripRequested:NO
  ];
  RCTJpegSanitizerAssertEqualData(safe, input, @"safe output bytes remain unchanged");
  RCTJpegSanitizerAssertEqualData(
    preserve,
    input,
    @"preserve output bytes remain unchanged"
  );
}

static void TestRejectsMalformedHeadersAndSegmentLengths(void)
{
  NSArray<NSData *> *invalid = @[
    [NSData data],
    RCTJpegSanitizerData({0xff, 0xd8}),
    RCTJpegSanitizerData({0x00, 0xd8, 0xff, 0xd9}),
    RCTJpegSanitizerData({0xff, 0xd8, 0x00, 0xd9}),
    RCTJpegSanitizerData({0xff, 0xd8, 0xff, 0x00, 0xff, 0xd9}),
    RCTJpegSanitizerData({0xff, 0xd8, 0xff, 0x02, 0x00, 0x02, 0xff, 0xd9}),
    RCTJpegSanitizerData({0xff, 0xd8, 0xff, 0xd8, 0xff, 0xd9}),
    RCTJpegSanitizerData({0xff, 0xd8, 0xff, 0xd0, 0xff, 0xd9}),
    RCTJpegSanitizerData({0xff, 0xd8, 0xff, 0xe1}),
    RCTJpegSanitizerData({0xff, 0xd8, 0xff, 0xe1, 0x00}),
    RCTJpegSanitizerData({0xff, 0xd8, 0xff, 0xe1, 0x00, 0x01, 0xff, 0xd9}),
    RCTJpegSanitizerData({0xff, 0xd8, 0xff, 0xe1, 0x00, 0x05, 0x11, 0xff, 0xd9}),
    RCTJpegSanitizerData({
      0xff, 0xd8,
      0xff, 0xdc, 0x00, 0x04, 0x00, 0x08,
      0xff, 0xda, 0x00, 0x08, 0x01, 0x01, 0x00, 0x00, 0x3f, 0x00,
      0xff, 0xd9,
    }),
    RCTJpegSanitizerData({0xff, 0xd8, 0xff, 0xda, 0x00, 0x02, 0xff, 0xd9}),
    RCTJpegSanitizerData({
      0xff, 0xd8,
      0xff, 0xda, 0x00, 0x08, 0x00, 0x01, 0x00, 0x00, 0x3f, 0x00,
      0xff, 0xd9,
    }),
    RCTJpegSanitizerData({
      0xff, 0xd8,
      0xff, 0xda, 0x00, 0x0a, 0x01, 0x01, 0x00, 0x00, 0x3f, 0x00,
      0x00, 0x00,
      0xff, 0xd9,
    }),
    RCTJpegSanitizerData({
      0xff, 0xd8,
      0xff, 0xda, 0x00, 0x10, 0x05,
      0x01, 0x00, 0x02, 0x00, 0x03, 0x00, 0x04, 0x00, 0x05, 0x00,
      0x00, 0x3f, 0x00,
      0xff, 0xd9,
    }),
    RCTJpegSanitizerData({
      0xff, 0xd8,
      0xff, 0xda, 0x00, 0x08, 0x01, 0x01, 0x00, 0x00, 0x3f, 0x00,
      0x11,
      0xff, 0xdc, 0x00, 0x03, 0x00,
      0xff, 0xd9,
    }),
    RCTJpegSanitizerData({0xff, 0xd8, 0xff, 0xd9}),
  ];
  for (NSUInteger index = 0; index < invalid.count; index += 1) {
    RCTJpegSanitizerAssert(
      [RCTImageCompressionJpegSegmentSanitizer
        sanitizeJpegData:invalid[index]
        stripRequested:YES
      ] == nil,
      [NSString stringWithFormat:@"rejects malformed header/segment case %lu", (unsigned long)index]
    );
  }
}

static void TestRejectsMalformedScanTermination(void)
{
  NSArray<NSData *> *invalid = @[
    RCTJpegSanitizerData({0xff, 0xd8, 0xff, 0xda, 0x00, 0x08, 0x01, 0x01, 0x00, 0x00, 0x3f, 0x00}),
    RCTJpegSanitizerData({0xff, 0xd8, 0xff, 0xda, 0x00, 0x08, 0x01, 0x01, 0x00, 0x00, 0x3f, 0x00, 0x11}),
    RCTJpegSanitizerData({0xff, 0xd8, 0xff, 0xda, 0x00, 0x08, 0x01, 0x01, 0x00, 0x00, 0x3f, 0x00, 0x11, 0xff}),
    RCTJpegSanitizerData({0xff, 0xd8, 0xff, 0xda, 0x00, 0x08, 0x01, 0x01, 0x00, 0x00, 0x3f, 0x00, 0x11, 0xff, 0xd8}),
    RCTJpegSanitizerData({0xff, 0xd8, 0xff, 0xda, 0x00, 0x08, 0x01, 0x01, 0x00, 0x00, 0x3f, 0x00, 0x11, 0xff, 0xd9, 0x00}),
    RCTJpegSanitizerData({
      0xff, 0xd8,
      0xff, 0xda, 0x00, 0x08, 0x01, 0x01, 0x00, 0x00, 0x3f, 0x00,
      0x11,
      0xff, 0xe1, 0x00, 0x04, 0x22, 0x33,
      0x44,
      0xff, 0xd9,
    }),
  ];
  for (NSUInteger index = 0; index < invalid.count; index += 1) {
    RCTJpegSanitizerAssert(
      [RCTImageCompressionJpegSegmentSanitizer
        sanitizeJpegData:invalid[index]
        stripRequested:YES
      ] == nil,
      [NSString stringWithFormat:@"rejects malformed scan/termination case %lu", (unsigned long)index]
    );
  }
}

int main(void)
{
  @autoreleasepool {
    TestRemovesMetadataBeforeAndBetweenScans();
    TestPreservesStuffedRestartAndNonSensitiveSegments();
    TestBypassesSafeAndPreserveOutputs();
    TestRejectsMalformedHeadersAndSegmentLengths();
    TestRejectsMalformedScanTermination();
    if (RCTJpegSanitizerFailureCount > 0) {
      fprintf(
        stderr,
        "iOS JPEG segment sanitizer tests failed: %lu/%lu assertions failed.\n",
        (unsigned long)RCTJpegSanitizerFailureCount,
        (unsigned long)RCTJpegSanitizerAssertionCount
      );
      return 1;
    }
    printf(
      "iOS JPEG segment sanitizer tests passed: %lu assertions across 5 groups.\n",
      (unsigned long)RCTJpegSanitizerAssertionCount
    );
  }
  return 0;
}
